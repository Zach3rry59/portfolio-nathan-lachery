import test from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { connectDatabase, disconnectDatabase } from '../src/config/database.js';
import { Project } from '../src/models/Project.js';
import { Contact } from '../src/models/Contact.js';
import { AdminSession } from '../src/models/AdminSession.js';
import { repository } from '../src/services/repository.js';
import { hashPassword } from '../src/services/password.js';
import { server } from './helpers.mjs';
const uri = process.env.MONGODB_TEST_URI;
test('Real MongoDB: indexes, authentication, CRUD, contact persistence and logout', { skip: !uri }, async t => {
  if (new URL(uri).pathname !== '/portfolio_test') throw new Error('Utiliser exclusivement la base jetable portfolio_test.');
  assert.equal(await connectDatabase(uri),true);
  t.after(async () => { await mongoose.connection.dropDatabase(); await disconnectDatabase(); });
  await Promise.all([Project.init(),Contact.init(),AdminSession.init()]);
  const password = 'Integration-test-password-only';
  const api = await server(t,repository,{ adminEmail:'admin@example.test',adminPasswordHash:await hashPassword(password) });
  const login = await api('/auth/login','POST',{ email:'admin@example.test',password });
  assert.equal(login.status,200); const { token } = await login.json();
  const fixture = { title:'Fixture MongoDB',slug:'integration-mongodb',shortDescription:'Données techniques isolées des projets publics.',category:'industry',technologies:[] };
  const response = await api('/projects','POST',fixture,token); assert.equal(response.status,201);
  const { data } = await response.json(); assert.ok(await Project.findById(data._id));
  assert.equal((await api('/projects','POST',fixture,token)).status,409);
  assert.equal((await (await api('/projects?category=industry')).json()).data.length,1);
  assert.equal((await api(`/projects/${data._id}`,'PATCH',{ category:'dev',order:3 },token)).status,200);
  assert.equal((await Project.findById(data._id)).category,'dev');
  assert.equal((await api('/contact','POST',{ name:'Test Mongo',email:'test@example.test',subject:'Test isolé',message:'Message uniquement utilisé pour vérifier MongoDB.' })).status,201);
  assert.equal(await Contact.countDocuments(),1);
  assert.equal((await api(`/projects/${data._id}`,'DELETE',undefined,token)).status,204);
  assert.equal(await Project.countDocuments(),0);
  assert.equal((await api('/auth/logout','POST',undefined,token)).status,204);
  assert.equal(await AdminSession.countDocuments(),0);
  assert.ok((await Contact.collection.indexes()).some(index=>index.expireAfterSeconds===15552000));
});
